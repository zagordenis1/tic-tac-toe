import type { Board } from "../core/Board";
import type { PlayerSymbol } from "../types/Symbol";
import type { Position } from "../types/Position";

/**
 * Контракт стратегії AI. Кожен рівень складності — це окрема реалізація
 * цього інтерфейсу. Завдяки цьому ми можемо легко замінити одну стратегію
 * іншою без змін в інших частинах коду — це класичний приклад патерна
 * Strategy.
 *
 * Стратегія отримує всю інформацію, потрібну для прийняття рішення, через
 * `AIContext`, але не має доступу до внутрішніх структур `Game` чи `Board`
 * на запис. Це гарантує, що жоден AI не «зіпсує» поточну партію — він
 * лише обчислює і повертає позицію.
 */
export interface AIStrategy {
  /**
   * Унікальне імʼя стратегії. Використовується для логування і
   * відображення в UI (наприклад «Думає Hard AI…»).
   */
  readonly name: string;

  /**
   * Обчислює бажаний хід поточного гравця. Гарантовано повертає
   * валідну позицію, на яку зараз є вільна клітинка. Якщо вільних
   * клітинок немає (це означає, що партія мала б закінчитися нічиєю),
   * стратегія має кинути помилку — але ми завжди викликаємо її лише
   * тоді, коли partнерські умови виконані.
   */
  decide(context: AIContext): Position;
}

/**
 * Усі дані, що потрібні стратегії для прийняття рішення. Окремий тип
 * допомагає не перевантажувати сигнатуру `decide` купою аргументів —
 * це типовий приклад техніки Introduce Parameter Object.
 */
export interface AIContext {
  readonly board: Board;
  readonly winLength: number;
  readonly forSymbol: PlayerSymbol;
}
