/**
 * Базовий контракт команди в патерні **Command**. Кожна операція над станом
 * гри інкапсулюється в окремому обʼєкті, який знає, як себе виконати
 * (`execute`) та як скасувати (`undo`). Завдяки цьому у нас є рівно одне
 * місце з логікою кожної дії — і ми можемо легко комбінувати команди в
 * стек для undo/redo.
 *
 * Команда параметризована типом стану `S`: вона приймає поточний стан і
 * повертає новий. Це робить команди чистими функціями над станом і
 * полегшує тестування.
 */
export interface Command<S> {
  /**
   * Імʼя команди — використовується для логів і для UI («Скасувати хід»).
   */
  readonly name: string;

  /**
   * Виконує команду над поточним станом і повертає новий стан.
   */
  execute(state: S): S;

  /**
   * Повертає попередній стан. Зазвичай команди зберігають всередині
   * себе той «минулий стан», з якого вони стартували, і просто його
   * віддають. Деякі команди (наприклад «перезапустити партію») можуть
   * не підтримувати undo — тоді вони повинні кинути помилку або повернути
   * вхідний стан як є.
   */
  undo(state: S): S;

  /**
   * Чи команда оборотна. Якщо `false`, історія її пропускає при undo.
   */
  readonly reversible: boolean;
}
